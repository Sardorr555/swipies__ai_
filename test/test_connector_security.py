    # -------------------------------------------------------------------------
    # 1. Primitives: AES-256-GCM (enc:v2:) and Tamper Resistance
    # -------------------------------------------------------------------------
    def test_crypto_primitives_aes256_gcm(self):
        plaintext = "super_secret_crm_api_key_12345"

        enc = encrypt_api_key(plaintext, self.master_secret)
        self.assertTrue(enc.startswith("enc:v2:"), f"Expected enc:v2: prefix, got {enc}")

        # Idempotency
        enc2 = encrypt_api_key(enc, self.master_secret)
        self.assertEqual(enc, enc2)

        # Decryption
        dec = decrypt_api_key(enc, self.master_secret)
        self.assertEqual(dec, plaintext)

        # Empty string handling
        self.assertEqual(encrypt_api_key("", self.master_secret), "")
        self.assertEqual(decrypt_api_key("", self.master_secret), "")

        # Tamper resistance: corrupted ciphertext tag must not raise uncaught exception, but fail safely
        corrupted = enc[:-4] + "AAAA"
        dec_corrupt = decrypt_api_key(corrupted, self.master_secret)
        self.assertEqual(dec_corrupt, corrupted, "Corrupted ciphertext should fail-safe without crashing")

    # -------------------------------------------------------------------------
    # 2. Fail-Closed Validation on Missing or Insecure Master Secrets
    # -------------------------------------------------------------------------
    def test_fail_closed_validation(self):
        # A. Empty key -> must raise InsecureSecretKeyError
        with self.assertRaises(InsecureSecretKeyError):
            validate_master_secret("")

        # B. Too short key (<32 bytes) -> must raise InsecureSecretKeyError
        with self.assertRaises(InsecureSecretKeyError):
            validate_master_secret("short-16-bytes!")

        # C. Known default keys -> must raise InsecureSecretKeyError
        with self.assertRaises(InsecureSecretKeyError):
            validate_master_secret("ragflow_single_global_instance_master_secret_2026")

        with self.assertRaises(InsecureSecretKeyError):
            validate_master_secret("ragflow")

        with self.assertRaises(InsecureSecretKeyError):
            validate_master_secret("infiniflow")

        # D. Encrypt with empty secret and no env var -> fails closed
        os.environ.pop("RAGFLOW_SECRET_KEY", None)
        with self.assertRaises(InsecureSecretKeyError):
            encrypt_api_key("some_secret", secret="")

    # -------------------------------------------------------------------------
    # 3. Cross-Language Compatibility: Python <-> Go Bidirectional Vectors
    # -------------------------------------------------------------------------
    def test_cross_language_compatibility(self):
        expected_plain = "cross-lang-test-secret-value-12345"

        # A. Vector generated by Go (utility.EncryptAPIKey with AES-256-GCM + HKDF):
        go_v2_vector = "enc:v2:nB4USVo0RRT4hDXHEFM71cQUXn7pQMO+yX8BCcYEy7Ti7onbWsiQWsGPdCItubMOkZFJwFGWbp9p9MzXgqg="
        dec_from_go = decrypt_api_key(go_v2_vector, self.master_secret)
        self.assertEqual(dec_from_go, expected_plain, "Python failed to decrypt Go AES-256-GCM HKDF ciphertext")

        # B. Python constant vector: verified to decrypt in both Python and Go
        py_v2_vector = "enc:v2:yqE1XB6mL4jEC7fDc+utp8iy4YFn6dtO2jHQVNvvhtPn2oceDAkD5S8mu6QeISVb0nDZB7n+i5V3+8AL+l4="
        dec_py_vector = decrypt_api_key(py_v2_vector, self.master_secret)
        self.assertEqual(dec_py_vector, expected_plain, "Python failed to decrypt its own constant vector")

        # C. Go legacy v1 vector (HMAC-SHA256 CTR) decrypted by Python:
        legacy_v1_vector = "enc:v1:MDEyMzQ1Njc4OWFiY2RlZi2J+E1szJ+OKGOCVomikPPcq0j8d0Yjn7GmJSVm2UwuvGA+XSQUssnHfH0HcjdVGcLw"
        dec_legacy = decrypt_api_key(legacy_v1_vector, self.master_secret)
        self.assertEqual(dec_legacy, expected_plain, "Python failed to decrypt legacy enc:v1: vector")

