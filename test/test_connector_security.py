    # 14. AI Provider Radius of Impact: Legacy enc:v1: Decryption & Key Rotation
    # -------------------------------------------------------------------------
    def test_ai_provider_legacy_v1_and_rotation_behavior(self):
        """
        ai_provider_service uses key_crypto.py for LLM API keys.
        Existing keys in production were encrypted under legacy enc:v1: (HMAC-SHA256 CTR).
        This test proves:
        1. An existing enc:v1: key decrypts properly with the original secret.
        2. When rotated to a new primary secret (with old key in RAGFLOW_SECRET_KEYS_ROTATION),
           the enc:v1: key continues to decrypt seamlessly.
        3. When a new key is encrypted, it automatically gets modern enc:v2: (AES-256-GCM).
        4. If secret changes without old key in rotation list, decryption fails safely
           without crashing, returning the ciphertext and logging an error.
        """
        old_ai_secret = "legacy-ai-provider-secret-key-32b!"
        raw_openai_key = "sk-proj-super-confidential-openai-api-key-12345"

        # Known enc:v1: vector generated with old_ai_secret
        # iv: 16 bytes "0123456789abcdef", payload encrypted with HMAC-CTR using old_ai_secret
        # We can construct or verify via decrypt_api_key
        legacy_v1_vector = "enc:v1:MDEyMzQ1Njc4OWFiY2RlZi2J+E1szJ+OKGOCVomikPPcq0j8d0Yjn7GmJSVm2UwuvGA+XSQUssnHfH0HcjdVGcLw"
        expected_plain = "cross-lang-test-secret-value-12345"

        # 1. Decrypt with matching master secret (self.master_secret)
        decrypted_primary = decrypt_api_key(legacy_v1_vector, self.master_secret)
        self.assertEqual(decrypted_primary, expected_plain, "Failed to decrypt legacy v1 with primary key")

        # 2. Key rotation: master secret changes to new_secret, old key moved to rotation list
        new_secret = "brand-new-primary-key-32bytes-ok!"
        os.environ["RAGFLOW_SECRET_KEY"] = new_secret
        os.environ["RAGFLOW_SECRET_KEYS_ROTATION"] = f"unrelated-key,{self.master_secret}"

        # decrypt_api_key with no explicit secret should use keyring and succeed
        decrypted_rotated = decrypt_api_key(legacy_v1_vector)
        self.assertEqual(decrypted_rotated, expected_plain, "Failed to decrypt legacy v1 via rotation keyring")

        # 3. New encryption under new primary key produces enc:v2:
        new_enc = encrypt_api_key("sk-proj-new-key-12345")
        self.assertTrue(new_enc.startswith("enc:v2:"), f"Expected enc:v2:, got: {new_enc}")
        self.assertEqual(decrypt_api_key(new_enc), "sk-proj-new-key-12345")

        # 4. Unknown key: neither primary nor rotation matches -> fails safely, returns ciphertext
        os.environ["RAGFLOW_SECRET_KEY"] = "completely-different-key-32bytes!!"
        os.environ.pop("RAGFLOW_SECRET_KEYS_ROTATION", None)
        failed_dec = decrypt_api_key(legacy_v1_vector)
        self.assertEqual(failed_dec, legacy_v1_vector, "Unknown key should safely return ciphertext without crash")


