    # 4. Key Rotation: Decryption via Keyring
    # -------------------------------------------------------------------------
    def test_key_rotation_keyring(self):
        old_key = "old-master-secret-key-rotated-2025"
        new_key = "new-master-secret-key-current-2026"
        secret_val = "pre-rotation-confidential-secret"

        # Encrypted under old key
        enc_old = encrypt_api_key(secret_val, old_key)
        self.assertTrue(enc_old.startswith("enc:v2:"))

        # Configure environment with new primary key and old key in rotation list
        os.environ["RAGFLOW_SECRET_KEY"] = new_key
        os.environ["RAGFLOW_SECRET_KEYS_ROTATION"] = f"other-key-1,{old_key},other-key-2"

        # decrypt_api_key without explicit secret uses environment keyring
        dec_val = decrypt_api_key(enc_old)
        self.assertEqual(dec_val, secret_val, "Key rotation keyring failed to decrypt ciphertext from retired key")

