    # 7. URL Credentials Sanitization and Rest-Encryption
    # -------------------------------------------------------------------------
    def test_url_credentials_sanitization_and_encryption(self):
        cfg = {
            "rss_url": "https://feed.example.com/rss?token=secret_query_token_123&category=news",
            "sitemap_url": "https://admin:my_secret_http_pass@sitemap.example.com/sitemap.xml",
            "credentials": {
                "instance_url": "https://service-user:p@ssword999@jira.corp.local",
                "client_id": "public-client-id-123",
            }
        }

        # 1. Detection
        self.assertTrue(has_embedded_url_credentials(cfg["rss_url"]))
        self.assertTrue(has_embedded_url_credentials(cfg["sitemap_url"]))
        self.assertTrue(has_embedded_url_credentials(cfg["credentials"]["instance_url"]))
        self.assertFalse(has_embedded_url_credentials("https://safe.example.com/feed.xml"))

        # 2. Masking
        masked = mask_connector_config(cfg)
        self.assertEqual(masked["rss_url"], "https://feed.example.com/rss?token=********&category=news")
        self.assertEqual(masked["sitemap_url"], "https://admin:********@sitemap.example.com/sitemap.xml")
        self.assertEqual(masked["credentials"]["instance_url"], "https://service-user:********@jira.corp.local")
        self.assertEqual(masked["credentials"]["client_id"], "public-client-id-123")

        # 3. Encryption at rest
        encrypted = encrypt_connector_config(cfg)
        self.assertTrue(encrypted["rss_url"].startswith("enc:v2:"))
        self.assertTrue(encrypted["sitemap_url"].startswith("enc:v2:"))
        self.assertTrue(encrypted["credentials"]["instance_url"].startswith("enc:v2:"))

        # 4. Decryption recovers original URLs
        decrypted = decrypt_connector_config(encrypted)
        self.assertEqual(decrypted["rss_url"], cfg["rss_url"])
        self.assertEqual(decrypted["sitemap_url"], cfg["sitemap_url"])
        self.assertEqual(decrypted["credentials"]["instance_url"], cfg["credentials"]["instance_url"])

