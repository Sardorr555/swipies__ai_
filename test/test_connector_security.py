    def test_syncer_decryption_and_oauth_refresh(self):
        stored_config = {
            "source": "gmail",
            "credentials": {
                "client_id": "gmail_client_id_123.apps.googleusercontent.com",
                "client_secret": "gmail_secret_456",
                "refresh_token": "original_refresh_token_789",
                "access_token": "expired_access_token_000",
            }
        }
        db_config = encrypt_connector_config(stored_config)
        self.assertTrue(db_config["credentials"]["client_secret"].startswith("enc:v2:"))
        self.assertTrue(db_config["credentials"]["refresh_token"].startswith("enc:v2:"))
        self.assertTrue(db_config["credentials"]["access_token"].startswith("enc:v2:"))

        # 1. Syncer starts: decrypts config to connect to Google API
        syncer_config = decrypt_connector_config(db_config)
        self.assertEqual(syncer_config["credentials"]["client_secret"], "gmail_secret_456")
        self.assertEqual(syncer_config["credentials"]["refresh_token"], "original_refresh_token_789")

        # 2. Syncer receives new OAuth access token from Google OAuth endpoint:
        refreshed_access_token = "brand_new_refreshed_access_token_from_google_api_999"
        update_payload = {
            "credentials": {
                "access_token": refreshed_access_token,
            }
        }

        # 3. Syncer writes back to DB via merge_updated_connector_config:
        updated_db_config = merge_updated_connector_config(db_config, update_payload)

        new_enc_token = updated_db_config["credentials"]["access_token"]
        self.assertTrue(new_enc_token.startswith("enc:v2:"), f"Refreshed token was saved as plaintext! Got: {new_enc_token}")
        self.assertNotEqual(new_enc_token, refreshed_access_token)

        recovered = decrypt_connector_config(updated_db_config)
        self.assertEqual(recovered["credentials"]["access_token"], refreshed_access_token)

