    # -------------------------------------------------------------------------
    # 9. Safe Update / Merge Pattern (Preserves Existing Secrets)
    # -------------------------------------------------------------------------
    def test_merge_updated_connector_config(self):
        stored_raw_config = {
            "source": "bitbucket",
            "credentials": {
                "username": "bb_admin",
                "app_password": "real_secret_password_12345",
                "account_id": "acc-9988",
            },
            "refresh_freq": 5
        }
        stored_enc_config = encrypt_connector_config(stored_raw_config)
        original_enc_password = stored_enc_config["credentials"]["app_password"]
        self.assertTrue(original_enc_password.startswith("enc:v2:"))

        # Scenario A: UI sends "********" mask placeholder
        incoming_ui_payload = {
            "credentials": {
                "username": "bb_admin",
                "app_password": "********",
                "account_id": "acc-9988",
            },
            "refresh_freq": 15
        }
        merged = merge_updated_connector_config(stored_enc_config, incoming_ui_payload)
        self.assertEqual(merged["refresh_freq"], 15)
        self.assertEqual(merged["credentials"]["app_password"], original_enc_password)

        decrypted_merged = decrypt_connector_config(merged)
        self.assertEqual(decrypted_merged["credentials"]["app_password"], "real_secret_password_12345")

        # Scenario B: User provides a real new password
        incoming_new_pw_payload = {
            "credentials": {
                "username": "bb_admin",
                "app_password": "brand_new_password_99999",
                "account_id": "acc-9988",
            },
            "refresh_freq": 15
        }
        merged_new_pw = merge_updated_connector_config(stored_enc_config, incoming_new_pw_payload)
        new_enc_password = merged_new_pw["credentials"]["app_password"]
        self.assertTrue(new_enc_password.startswith("enc:v2:"))
        self.assertNotEqual(new_enc_password, original_enc_password)

        decrypted_new = decrypt_connector_config(merged_new_pw)
        self.assertEqual(decrypted_new["credentials"]["app_password"], "brand_new_password_99999")

        # Scenario C: UI sends empty string for existing secret
        incoming_empty_pw = {
            "credentials": {
                "username": "bb_admin",
                "app_password": "",
                "account_id": "acc-9988",
            }
        }
        merged_empty = merge_updated_connector_config(stored_enc_config, incoming_empty_pw)
        self.assertEqual(merged_empty["credentials"]["app_password"], original_enc_password)

