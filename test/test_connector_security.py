    # 11. Migration CLI: Find Unencrypted, Rollback Reverse, Key Rotation
    # -------------------------------------------------------------------------
    def test_migration_cli_helpers(self):
        plaintext_cfg = {
            "credentials": {
                "instance_url": "https://example.com",
                "jira_api_token": "raw_token_xyz",
                "nested_auth": {
                    "private_key": "raw_key_abc",
                    "public_field": "visible"
                }
            }
        }
        # 1. Plaintext config has 2 unencrypted fields
        unenc = find_unencrypted_keys(plaintext_cfg)
        self.assertIn("credentials.jira_api_token", unenc)
        self.assertIn("credentials.nested_auth.private_key", unenc)
        self.assertNotIn("credentials.instance_url", unenc)

        # 2. Encrypted config has 0 unencrypted fields
        enc_cfg = encrypt_connector_config(plaintext_cfg)
        self.assertEqual(len(find_unencrypted_keys(enc_cfg)), 0)

        # 3. Encrypted config has 2 encrypted fields
        enc_fields = find_encrypted_keys(enc_cfg)
        self.assertIn("credentials.jira_api_token", enc_fields)
        self.assertIn("credentials.nested_auth.private_key", enc_fields)

        # 4. Reverse rollback restores exact plaintext
        reversed_cfg = decrypt_connector_config(enc_cfg)
        self.assertEqual(reversed_cfg, plaintext_cfg)
        self.assertEqual(len(find_encrypted_keys(reversed_cfg)), 0)

