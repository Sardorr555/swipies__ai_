import { AD_PHRASES } from './phrases';

export function translateAdText(keyOrText: string, lang: AdLanguage, fallback?: string): string {
  if (!keyOrText) return keyOrText;
  const trimmed = keyOrText.trim();

  // 1. Direct match in AD_TRANSLATIONS for requested language
  if (AD_TRANSLATIONS[lang]?.[trimmed]) {
    return AD_TRANSLATIONS[lang][trimmed];
  }

  // 2. Direct match in AD_PHRASES dictionary
  const phrase = AD_PHRASES[trimmed];
  if (phrase) {
    if (lang === 'en' && phrase.en) return phrase.en;
    if (lang === 'uz' && phrase.uz) return phrase.uz;
    return trimmed;
  }

  // 3. Fallback to specified fallback
  if (fallback !== undefined) return fallback;

  // 4. Russian fallback or original string
  if (lang === 'ru') return trimmed;
  return AD_TRANSLATIONS['en']?.[trimmed] || trimmed;
}
